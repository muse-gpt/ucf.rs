/// Looks a preset up by name.
#[must_use]
pub fn preset(name: &str) -> Option<SfxSpec> {
    PRESETS.iter().find(|p| p.name == name).map(|p| p.spec.clone())
}

/// Every preset name, in catalogue order.
#[must_use]
pub fn preset_names() -> Vec<&'static str> {
    PRESETS.iter().map(|p| p.name).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    const ALL_FAMILIES: [Family; 8] = [
        Family::Whoosh,
        Family::Impact,
        Family::Riser,
        Family::Tick,
        Family::Glitch,
        Family::Sub,
        Family::Ambience,
        Family::Sparkle,
    ];

    #[test]
    fn family_names_round_trip_through_parse() {
        for family in ALL_FAMILIES {
            assert_eq!(Family::parse(family.as_str()), Some(family));
            let value = serde_json::to_string(&family).expect("serialisable");
            assert_eq!(value, format!("\"{}\"", family.as_str()), "serde tag must equal as_str");
        }
        assert_eq!(Family::parse("nope"), None);
    }

    #[test]
    fn seed_default_is_unified() {
        assert_eq!(SfxSpec::new(Family::Tick, 0.1).seed, DEFAULT_SEED);
        let parsed: SfxSpec = serde_json::from_str(r#"{"family":"tick","duration":0.1}"#).expect("wire");
        assert_eq!(parsed.seed, DEFAULT_SEED, "serde default must equal the constructor default");
        assert_eq!(parsed, SfxSpec::new(Family::Tick, 0.1));
    }

    #[test]
    fn serde_wire_shape_is_kebab_tag_and_camel_fields() {
        let parsed: SfxSpec =
            serde_json::from_str(r#"{"family":"glitch","duration":0.8,"seed":53,"pitch":1.0,"brightness":0.7}"#).expect("wire");
        assert_eq!(parsed, preset("glitch-data").expect("preset"));
        let json = serde_json::to_string(&parsed).expect("serialisable");
        for key in ["family", "seed", "duration", "pitch", "brightness", "intensity", "pan"] {
            assert!(json.contains(&format!("\"{key}\"")), "missing camelCase key {key} in {json}");
        }
        assert!(json.contains("\"glitch\""));
    }

    #[test]
    fn presets_are_unique_and_valid() {
        let names = preset_names();
        let unique: std::collections::BTreeSet<_> = names.iter().collect();
        assert_eq!(unique.len(), names.len());
        for entry in PRESETS {
            assert!(entry.spec.duration > 0.0);
            entry.spec.validate().expect("every shipped preset passes the range contract");
            assert_eq!(preset(entry.name).as_ref(), Some(&entry.spec));
        }
    }

    #[test]
    fn range_contract_rejects_out_of_bounds() {
        let bad = [
            ("duration", {
                let mut s = SfxSpec::new(Family::Tick, 0.009);
                s.duration = 0.009;
                s
            }),
            ("pitch", SfxSpec::new(Family::Tick, 0.1).with(1, 0.04, 0.5)),
            ("brightness", SfxSpec::new(Family::Tick, 0.1).with(1, 1.0, 1.5)),
            ("intensity", {
                let mut s = SfxSpec::new(Family::Tick, 0.1);
                s.intensity = -0.1;
                s
            }),
            ("nan duration", {
                let mut s = SfxSpec::new(Family::Tick, 0.1);
                s.duration = f32::NAN;
                s
            }),
            ("inf pitch", {
                let mut s = SfxSpec::new(Family::Tick, 0.1);
                s.pitch = f32::INFINITY;
                s
            }),
            ("nan pan", {
                let mut s = SfxSpec::new(Family::Tick, 0.1);
                s.pan = f32::NAN;
                s
            }),
        ];
        for (label, spec) in bad {
            let error = spec.validate().expect_err("{label} must be rejected");
            assert_eq!(error.code(), "invalid_input", "{label}");
        }
        SfxSpec::new(Family::Tick, MIN_DURATION).validate().expect("the edge duration is valid");
        SfxSpec::new(Family::Tick, 0.1).with(0, MIN_PITCH, 0.0).validate().expect("the edge pitch and brightness are valid");
    }
}
